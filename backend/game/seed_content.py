def ensure_bots():
    for item in DEFAULT_BOTS:
        defaults = {
            "name": item["name"],
            "color": item["color"],
            "avatar": str(item.get("avatar") or ""),
            "accuracy": item.get("accuracy", float(site_get("bot_accuracy"))),
            "delay_min": item.get("delay_min", float(site_get("bot_delay_min"))),
            "delay_max": item.get("delay_max", float(site_get("bot_delay_max"))),
            "is_active": True,
            "count_for_leaderboard": bool(item.get("count_for_leaderboard", False)),
            "order": item["order"],
            "modes": list(item.get("modes") or ["multiplayer"]),
        }
        bot, created = AiBot.objects.get_or_create(key=item["key"], defaults=defaults)
        if created:
            continue
        changed = []
        # Ne prepisuj admin urejanj; dopolni samo manjkajoče modes/avatar.
        if not bot.modes:
            bot.modes = list(item.get("modes") or ["multiplayer"])
            changed.append("modes")
        if not bot.avatar and item.get("avatar"):
            bot.avatar = str(item["avatar"])
            changed.append("avatar")
        if changed:
            bot.save(update_fields=changed)


def ensure_bonuses_and_friends():
    for item in DEFAULT_BONUSES:
        BonusDefinition.objects.update_or_create(
            key=item["key"],
            defaults={
                "name": item["name"],
                "description": item["description"],
                "bonus_kind": item["bonus_kind"],
                "effect_key": item["effect_key"],
                "modes": item["modes"],
                "config": item["config"],
                "is_active": True,
                "order": item["order"],
            },
        )
    for item in DEFAULT_FRIENDS:
        defaults = {
            "name": item["name"],
            "title": item["title"],
            "bio": item["bio"],
            "specialty_categories": item["specialty_categories"],
            "reliability": item["reliability"],
            "out_of_specialty_reliability": item["out_of_specialty_reliability"],
            "avatar_color": item["avatar_color"],
            "avatar": str(item.get("avatar") or ""),
            "is_active": True,
            "order": item["order"],
        }
        friend, created = PhoneFriend.objects.get_or_create(key=item["key"], defaults=defaults)
        if created:
            continue
        # Ne prepisuj admin urejanj; dopolni samo manjkajoči avatar.
        if not friend.avatar and item.get("avatar"):
            friend.avatar = str(item["avatar"])
            friend.save(update_fields=["avatar"])
    ensure_bots()
